CREATE TABLE professionals (
    professional_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid UNIQUE REFERENCES users(user_id) ON DELETE SET NULL,
    document_type varchar(20) NOT NULL,
    document_number varchar(30) NOT NULL,
    first_name varchar(100) NOT NULL,
    last_name varchar(100) NOT NULL,
    license_number varchar(50) NOT NULL UNIQUE,
    phone_e164 varchar(15),
    color_tag varchar(7),
    google_calendar_id varchar(255),
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,
    UNIQUE (document_type, document_number)
);

CREATE TABLE specialties (
    specialty_id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name varchar(100) NOT NULL UNIQUE,
    default_duration_minutes int NOT NULL DEFAULT 30,
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE professional_specialties (
    professional_id uuid NOT NULL REFERENCES professionals(professional_id),
    specialty_id bigint NOT NULL REFERENCES specialties(specialty_id),
    active boolean NOT NULL DEFAULT true,
    PRIMARY KEY (professional_id, specialty_id)
);
