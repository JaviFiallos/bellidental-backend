CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE professional_schedules (
    professional_schedule_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professional_id uuid NOT NULL,
    weekday smallint,
    specific_date date,
    start_time time,
    end_time time,
    available boolean NOT NULL DEFAULT true,
    active boolean NOT NULL DEFAULT true,
    CONSTRAINT fk_schedules_professional FOREIGN KEY (professional_id) REFERENCES professionals (professional_id),
    CONSTRAINT schedules_date_check CHECK ((weekday IS NULL) <> (specific_date IS NULL)),
    CONSTRAINT schedules_weekday_check CHECK (weekday BETWEEN 1 AND 7),
    CONSTRAINT schedules_time_check CHECK (available = false OR (start_time IS NOT NULL AND end_time > start_time))
);

CREATE INDEX idx_professional_schedules_weekday ON professional_schedules (professional_id, weekday);
CREATE INDEX idx_professional_schedules_specific_date ON professional_schedules (professional_id, specific_date);

CREATE TABLE appointments (
    appointment_id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
    patient_id uuid NOT NULL,
    professional_id uuid NOT NULL,
    specialty_id bigint NOT NULL,
    start_at timestamptz NOT NULL,
    end_at timestamptz NOT NULL,
    status varchar(12) NOT NULL DEFAULT 'PENDING',
    source varchar(12) NOT NULL,
    reason varchar(255),
    notes text,
    checked_in_at timestamptz,
    rescheduled_from_id uuid UNIQUE,
    google_event_id varchar(255),
    created_by uuid NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_appointments_patient FOREIGN KEY (patient_id) REFERENCES patients (patient_id),
    CONSTRAINT fk_appointments_professional_specialty FOREIGN KEY (professional_id, specialty_id) REFERENCES professional_specialties (professional_id, specialty_id),
    CONSTRAINT fk_appointments_created_by FOREIGN KEY (created_by) REFERENCES users (user_id),
    CONSTRAINT fk_appointments_rescheduled_from FOREIGN KEY (rescheduled_from_id) REFERENCES appointments (appointment_id),
    CONSTRAINT appointments_status_check CHECK (status IN ('PENDING', 'CONFIRMED', 'ATTENDED', 'CANCELLED', 'NO_SHOW', 'RESCHEDULED')),
    CONSTRAINT appointments_source_check CHECK (source IN ('RECEPTION', 'PROFESSIONAL', 'BOT', 'WALK_IN')),
    CONSTRAINT appointments_time_check CHECK (end_at > start_at),
    CONSTRAINT appointments_no_overlap EXCLUDE USING gist (
        professional_id WITH =,
        tstzrange(start_at, end_at) WITH &&
    ) WHERE (status NOT IN ('CANCELLED', 'NO_SHOW', 'RESCHEDULED'))
);

CREATE INDEX idx_appointments_professional_start ON appointments (professional_id, start_at);
CREATE INDEX idx_appointments_patient_start ON appointments (patient_id, start_at);
CREATE INDEX idx_appointments_status ON appointments (status);
