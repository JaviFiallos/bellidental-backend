CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE icd10_codes (
    icd10_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(10) NOT NULL UNIQUE,
    description varchar(500) NOT NULL,
    category varchar(255),
    active boolean NOT NULL DEFAULT true
);

CREATE INDEX idx_icd10_code_prefix ON icd10_codes (code text_pattern_ops);
CREATE INDEX idx_icd10_description_trgm ON icd10_codes USING gin (description gin_trgm_ops);
CREATE INDEX idx_patients_full_name_trgm ON patients USING gin ((first_name || ' ' || last_name) gin_trgm_ops);

