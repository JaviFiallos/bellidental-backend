CREATE TABLE revision_info (
    revision_id bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_at timestamptz NOT NULL,
    user_id     uuid        REFERENCES users(user_id)
);

CREATE TABLE patients_aud (
    patient_id                   uuid         NOT NULL,
    rev                          bigint       NOT NULL REFERENCES revision_info(revision_id),
    revtype                      smallint,
    document_type                varchar(20),
    document_number              varchar(30),
    first_name                   varchar(100),
    last_name                    varchar(100),
    birth_date                   date,
    sex                          char(1),
    blood_type                   varchar(3),
    phone_e164                   varchar(15),
    email                        varchar(150),
    admin_notes                  text,
    emergency_contact_name       varchar(150),
    emergency_contact_phone_e164 varchar(15),
    active                       boolean,
    created_at                   timestamptz,
    updated_at                   timestamptz,
    deleted_at                   timestamptz,
    PRIMARY KEY (patient_id, rev)
);

CREATE TABLE clinical_records_aud (
    clinical_record_id uuid        NOT NULL,
    rev                bigint      NOT NULL REFERENCES revision_info(revision_id),
    revtype            smallint,
    patient_id         uuid,
    record_number      varchar(20),
    opened_at          date,
    opened_by          uuid,
    no_known_history   boolean,
    current_medication text,
    created_at         timestamptz,
    updated_at         timestamptz,
    PRIMARY KEY (clinical_record_id, rev)
);

CREATE TABLE medical_history_entries_aud (
    medical_history_entry_id     uuid        NOT NULL,
    rev                          bigint      NOT NULL REFERENCES revision_info(revision_id),
    revtype                      smallint,
    clinical_record_id           uuid,
    medical_history_condition_id bigint,
    scope                        varchar(8),
    relative                     varchar(30),
    description                  text,
    active                       boolean,
    recorded_at                  timestamptz,
    voided_at                    timestamptz,
    PRIMARY KEY (medical_history_entry_id, rev)
);

CREATE TABLE appointments_aud (
    appointment_id        uuid         NOT NULL,
    rev                   bigint       NOT NULL REFERENCES revision_info(revision_id),
    revtype               smallint,
    patient_id            uuid,
    professional_id       uuid,
    specialty_id          bigint,
    start_at              timestamptz,
    end_at                timestamptz,
    status                varchar(12),
    source                varchar(12),
    reason                varchar(255),
    notes                 text,
    checked_in_at         timestamptz,
    rescheduled_from_id   uuid,
    google_event_id       varchar(255),
    created_by            uuid,
    created_at            timestamptz,
    updated_at            timestamptz,
    PRIMARY KEY (appointment_id, rev)
);

CREATE TABLE encounters_aud (
    encounter_id          uuid         NOT NULL,
    rev                   bigint       NOT NULL REFERENCES revision_info(revision_id),
    revtype               smallint,
    appointment_id        uuid,
    professional_id       uuid,
    start_at              timestamptz,
    end_at                timestamptz,
    closed_at             timestamptz,
    chief_complaint       text,
    current_illness       text,
    bp_systolic           smallint,
    bp_diastolic          smallint,
    heart_rate            smallint,
    temperature           decimal(4,1),
    respiratory_rate      smallint,
    stomatognathic_exam   text,
    stomatognathic_regions smallint[],
    periodontal_disease   varchar(10),
    malocclusion          varchar(10),
    fluorosis             varchar(10),
    diagnostic_exams      varchar(20)[],
    plan_description      text,
    status                varchar(10),
    voided_at             timestamptz,
    void_reason           text,
    created_at            timestamptz,
    updated_at            timestamptz,
    PRIMARY KEY (encounter_id, rev)
);

CREATE TABLE encounter_diagnoses_aud (
    encounter_diagnosis_id uuid        NOT NULL,
    rev                    bigint      NOT NULL REFERENCES revision_info(revision_id),
    revtype                smallint,
    encounter_id           uuid,
    icd10_id               bigint,
    certainty              varchar(12),
    notes                  text,
    created_at             timestamptz,
    voided_at              timestamptz,
    PRIMARY KEY (encounter_diagnosis_id, rev)
);

CREATE TABLE dental_findings_aud (
    dental_finding_id   uuid        NOT NULL,
    rev                 bigint      NOT NULL REFERENCES revision_info(revision_id),
    revtype             smallint,
    encounter_id        uuid,
    tooth_code          smallint,
    end_tooth_code      smallint,
    surface_code        char(1),
    dental_condition_id bigint,
    status              varchar(8),
    grade               smallint,
    notes               text,
    created_at          timestamptz,
    voided_at           timestamptz,
    PRIMARY KEY (dental_finding_id, rev)
);

CREATE TABLE performed_treatments_aud (
    performed_treatment_id uuid         NOT NULL,
    rev                    bigint       NOT NULL REFERENCES revision_info(revision_id),
    revtype                smallint,
    encounter_id           uuid,
    treatment_id           bigint,
    encounter_diagnosis_id uuid,
    dental_finding_id      uuid,
    tooth_code             smallint,
    surface_code           char(1),
    quantity               integer,
    price                  decimal(10,2),
    notes                  text,
    created_at             timestamptz,
    voided_at              timestamptz,
    void_reason            text,
    PRIMARY KEY (performed_treatment_id, rev)
);

CREATE TABLE prescriptions_aud (
    prescription_id        uuid        NOT NULL,
    rev                    bigint      NOT NULL REFERENCES revision_info(revision_id),
    revtype                smallint,
    encounter_id           uuid,
    encounter_diagnosis_id uuid,
    prescribed_at          timestamptz,
    general_instructions   text,
    status                 varchar(10),
    voided_at              timestamptz,
    created_at             timestamptz,
    PRIMARY KEY (prescription_id, rev)
);

CREATE TABLE prescription_items_aud (
    prescription_item_id uuid         NOT NULL,
    rev                  bigint       NOT NULL REFERENCES revision_info(revision_id),
    revtype              smallint,
    prescription_id      uuid,
    medication_id        bigint,
    medication_preset_id bigint,
    dose                 varchar(100),
    frequency            varchar(100),
    duration             varchar(100),
    quantity             varchar(50),
    instructions         text,
    PRIMARY KEY (prescription_item_id, rev)
);

CREATE TABLE payments_aud (
    payment_id     uuid          NOT NULL,
    rev            bigint        NOT NULL REFERENCES revision_info(revision_id),
    revtype        smallint,
    patient_id     uuid,
    encounter_id   uuid,
    amount         decimal(10,2),
    method         varchar(20),
    receipt_number varchar(30),
    paid_at        timestamptz,
    received_by    uuid,
    voided_at      timestamptz,
    void_reason    text,
    PRIMARY KEY (payment_id, rev)
);
