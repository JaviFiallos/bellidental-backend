CREATE TABLE clinical_records (
  clinical_record_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  patient_id UUID NOT NULL UNIQUE REFERENCES patients(patient_id),
  record_number VARCHAR(20) NOT NULL UNIQUE,
  opened_at DATE NOT NULL,
  opened_by UUID NOT NULL REFERENCES professionals(professional_id),
  no_known_history BOOLEAN NOT NULL DEFAULT false,
  current_medication TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE medical_history_conditions (
  medical_history_condition_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name VARCHAR(100) NOT NULL UNIQUE,
  display_order SMALLINT NOT NULL,
  active BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE medical_history_entries (
  medical_history_entry_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  clinical_record_id UUID NOT NULL REFERENCES clinical_records(clinical_record_id),
  medical_history_condition_id BIGINT NOT NULL REFERENCES medical_history_conditions(medical_history_condition_id),
  scope VARCHAR(8) NOT NULL CHECK (scope IN ('PERSONAL', 'FAMILY')),
  relative VARCHAR(30),
  description TEXT,
  active BOOLEAN NOT NULL DEFAULT true,
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  voided_at TIMESTAMPTZ
);

CREATE INDEX idx_medical_history_entries_clinical_record_id ON medical_history_entries(clinical_record_id);

CREATE SEQUENCE clinical_record_number_seq START 1;

